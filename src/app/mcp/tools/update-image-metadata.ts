import { z } from "zod";
import { eq, or } from "drizzle-orm";
import { revalidatePath } from "next/cache";
import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { db } from "@/lib/db";
import { images } from "@/lib/db/schema";
import { mcpVoiceGate } from "@/lib/voice/gate-log";
import { readOverride } from "@/lib/voice/gate";
import type { ToolContext } from "./index";

export function registerUpdateImageMetadata(server: McpServer, ctx: ToolContext) {
  server.registerTool(
    "update_image_metadata",
    {
      title: "Update image metadata",
      description:
        "Update an image's description and/or tags. Identify the image by UUID, filename, or pathname. Pass only the fields you want to change. Use this after looking at an image (via its public URL) to write back the description and tags.",
      inputSchema: {
        imageIdOrPath: z
          .string()
          .min(1)
          .describe("The image's UUID, filename, or pathname."),
        description: z
          .string()
          .max(2000)
          .optional()
          .describe(
            "Description of the image, 1-2 sentences. Also used as alt text.",
          ),
        tags: z
          .array(z.string())
          .optional()
          .describe(
            "Array of lowercase, hyphen-separated custom tags. Use existing library taxonomy when applicable.",
          ),
        voiceOverride: z
          .object({ reason: z.string().min(8) })
          .optional()
          .describe(
            "Only when the voice gate refused this text AND Jesper explicitly approved this exact text: his words as the reason. Logged. Never on your own.",
          ),
      },
    },
    async ({ imageIdOrPath, description, tags, voiceOverride }) => {
      const looksLikeUuid =
        /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(
          imageIdOrPath,
        );

      const condition = looksLikeUuid
        ? or(
            eq(images.id, imageIdOrPath),
            eq(images.filename, imageIdOrPath),
            eq(images.pathname, imageIdOrPath),
          )
        : or(
            eq(images.filename, imageIdOrPath),
            eq(images.pathname, imageIdOrPath),
          );

      const existing = await db
        .select()
        .from(images)
        .where(condition!)
        .limit(1);

      if (existing.length === 0) {
        return {
          isError: true,
          content: [
            {
              type: "text" as const,
              text: `No image found matching "${imageIdOrPath}".`,
            },
          ],
        };
      }

      const image = existing[0];

      // the description is the alt text a screen reader speaks: judged on what this edit adds
      const gate = await mcpVoiceGate(
        "update_image_metadata",
        ctx,
        [{ field: "description", text: description, before: image.description }],
        readOverride(voiceOverride),
      );
      if (gate.refuse) return gate.refuse;

      const patch: Partial<typeof images.$inferInsert> = {
        updatedAt: new Date(),
        reviewed: true,
        tagsAutoGenerated: false,
      };

      if (description !== undefined) patch.description = description;
      if (tags !== undefined) patch.customTags = tags;

      if (description === undefined && tags === undefined) {
        return {
          content: [
            {
              type: "text" as const,
              text: "No changes provided. Pass at least one of: description, tags.",
            },
          ],
        };
      }

      await db
        .update(images)
        .set(patch)
        .where(eq(images.id, image.id));

      revalidatePath("/admin/images");

      const changed = [];
      if (description !== undefined) changed.push("description");
      if (tags !== undefined) changed.push("customTags");

      return {
        content: [
          {
            type: "text" as const,
            text: `Updated metadata for "${image.filename}". Changed: ${changed.join(", ")}. Marked as reviewed.${gate.note ? `\n\n${gate.note}` : ""}`,
          },
        ],
      };
    },
  );
}
